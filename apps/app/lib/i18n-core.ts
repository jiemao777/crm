export type TranslationKey = keyof typeof DICT;

export function isLanguage(value: unknown): value is Language {
	return value === "zh" || value === "en";
}

export function resolveLanguage(value: unknown): Language {
	return isLanguage(value) ? value : DEFAULT_LANGUAGE;
}

export function localeFor(language: Language): Locale {
	return language === "zh" ? "zh-CN" : "en-US";
}

export function translate(
	language: Language,
	key: TranslationKey,
	values?: TranslationValues,
): string {
	const message = DICT[key][language];
	if (!values) return message;
	return message.replace(/\{([A-Za-z0-9_]+)\}/g, (match, token: string) =>
		Object.hasOwn(values, token) ? String(values[token]) : match,
	);
}

export function formatRelativeTime(
	iso: string | null | undefined,
	language: Language,
): string {
	if (!iso) return "—";
	const then = new Date(iso).getTime();
	if (!Number.isFinite(then)) return "—";
	const difference = then - Date.now();
	const absolute = Math.abs(difference);
	const minute = 60_000;
	const hour = 60 * minute;
	const day = 24 * hour;
	if (absolute >= 30 * day) {
		return new Date(iso).toLocaleDateString(localeFor(language), {
			month: "short",
			day: "numeric",
		});
	}
	const [amount, unit] =
		absolute < minute
			? ([0, "second"] as const)
			: absolute < hour
				? ([Math.round(difference / minute), "minute"] as const)
				: absolute < day
					? ([Math.round(difference / hour), "hour"] as const)
					: ([Math.round(difference / day), "day"] as const);
	return new Intl.RelativeTimeFormat(localeFor(language), {
		numeric: "auto",
		style: "narrow",
	}).format(amount, unit);
}
